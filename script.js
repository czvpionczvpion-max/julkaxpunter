  const buttons = document.querySelectorAll("[data-lang]");
  const metaDesc = document.querySelector('meta[name="description"]');
  let lang = "pl";

  function apply() {
    const t = I18N[lang] || I18N.pl;
    document.documentElement.lang = lang;
    document.title = t["meta.title"];
    if (metaDesc) metaDesc.setAttribute("content", t["meta.desc"]);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (t[key]) el.textContent = t[key];
    });
    buttons.forEach((btn) => {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });

    document.querySelectorAll("[data-copy]").forEach((el) => {
      el.setAttribute("aria-label", `${t["code.copy"]} ${el.getAttribute("data-copy")}`);
    });
  }

  async function copyCode(el) {
    const code = el.getAttribute("data-copy") || "";
    try {
      await navigator.clipboard.writeText(code);
    } catch {
      const field = document.createElement("textarea");
      field.value = code;
      field.setAttribute("readonly", "");
      field.style.position = "fixed";
      field.style.left = "-9999px";
      document.body.appendChild(field);
      field.select();
      document.execCommand("copy");
      field.remove();
    }
    el.classList.add("is-copied");
    window.setTimeout(() => el.classList.remove("is-copied"), 1600);
  }

  function setLang(next) {
    lang = next === "en" ? "en" : "pl";
    localStorage.setItem("lang", lang);
    const url = new URL(window.location.href);
    if (lang === "pl") url.searchParams.delete("lang");
    else url.searchParams.set("lang", "en");
    window.history.replaceState({}, "", url);
    apply();
  }

  const params = new URLSearchParams(window.location.search);
  const saved = localStorage.getItem("lang");
  lang = params.get("lang") === "en" || saved === "en" ? "en" : "pl";

  buttons.forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
  });

  document.querySelectorAll("[data-copy]").forEach((el) => {
    el.addEventListener("click", () => copyCode(el));
  });

  const gate = document.querySelector(".gate");
  const shell = document.querySelectorAll(".topbar, main, .footer");

  function unlock() {
    document.documentElement.classList.add("age-ok");
    shell.forEach((el) => el.removeAttribute("inert"));
  }

  if (document.documentElement.classList.contains("age-ok")) {
    unlock();
  } else if (gate) {
    const enter = gate.querySelector("[data-gate='enter']");
    if (enter) enter.focus();
    gate.addEventListener("click", (event) => {
      const btn = event.target.closest("[data-gate]");
      if (!btn) return;
      if (btn.getAttribute("data-gate") === "enter") {
        try { sessionStorage.setItem("age18", "1"); } catch (e) {}
        gate.classList.add("is-out");
        window.setTimeout(unlock, 420);
      } else {
        gate.classList.add("is-denied");
      }
    });
  }

  apply();
